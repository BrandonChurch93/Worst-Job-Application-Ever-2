// A sign of a font: `w` dots wide and `rows.length` tall, each row a number whose bit `w - 1 - x` is the dot at x.
export interface Glyph { w: number; rows: number[] }

const read = (rows: string[], tall: number): Glyph => {
  const w = rows.reduce((m, r) => Math.max(m, r.length), 0)
  const out: number[] = []
  for (let y = 0; y < tall; y++) {
    const r = rows[y] ?? ''
    let bits = 0
    for (let x = 0; x < w; x++) bits = (bits << 1) | (r[x] === '#' ? 1 : 0)
    out.push(bits)
  }
  return { w, rows: out }
}

export const text: Map<string, Glyph> = new Map(Object.entries(T).map(([c, rows]) => [c, read(rows.split('/'), TEXT_UP + TEXT_DOWN)]))
text.set(' ', { w: 2, rows: new Array<number>(TEXT_UP + TEXT_DOWN).fill(0) })
// A sign the font does not hold is a small open box, so a missing sign is seen and never guessed.
const BOX: Glyph = read(['....', '....', '####', '#..#', '#..#', '#..#', '####'], TEXT_UP + TEXT_DOWN)
const SAME: Record<string, string> = { '\u2019': "'", '\u2018': "'", '\u201c': '"', '\u201d': '"', '\u2013': '-', '\u2014': '-' }
export const glyph = (c: string): Glyph => text.get(SAME[c] ?? c) ?? BOX
export const hasGlyph = (c: string): boolean => text.has(SAME[c] ?? c)

export const score: Glyph[] = S.map((rows) => read(rows.split('/'), SCORE_H))

export const dot = (g: Glyph, x: number, y: number): boolean => x >= 0 && x < g.w && y >= 0 && y < g.rows.length && ((g.rows[y]! >> (g.w - 1 - x)) & 1) === 1
